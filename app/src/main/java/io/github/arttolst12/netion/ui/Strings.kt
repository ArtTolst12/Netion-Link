enum class AppLanguage(
    val code: String,
    val nativeTitle: String
) {
    // 1-7 Европейские
    RU("ru", "Русский"),
    EN("en", "English"),
    DE("de", "Deutsch"),
    FR("fr", "Français"),
    ES("es", "Español"),
    PT("pt", "Português"),
    PL("pl", "Polski"),

    // 8-10 Азиатские
    ZH("zh", "简体中文"),
    JA("ja", "日本語"),
    KO("ko", "한국어");

    companion object {
        fun fromSystemLocale(): AppLanguage {
            val lang = java.util.Locale.getDefault().language.lowercase(java.util.Locale.ROOT)
            return values().firstOrNull { it.code == lang } ?: EN
        }
    }
}

